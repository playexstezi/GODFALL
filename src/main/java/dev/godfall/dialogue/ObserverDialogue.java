package dev.godfall.dialogue;
import java.util.List;
public final class ObserverDialogue {
    private static final List<String> DEATH_LINES = List.of(
            "Ну вот. А я надеялся, что ты хотя бы сегодня справишься.",
            "Не переживай. В прошлый раз ты продержался ещё меньше.",
            "Опять? Может, на этот раз попробуем думать головой?",
            "Я уже перестал считать. Хотя нет, вру. Мне нравится наблюдать.",
            "Создатель миров проиграл обычному существу. Какое достижение.",
            "Ты ведь помнишь, что обещал больше не повторять эту ошибку?",
            "Каждая смерть что-то оставляет после себя. Ты скоро это заметишь.",
            "Интересно, сколько версий тебя уже осталось здесь?",
            "Не смотри так удивлённо. Мы оба знали, чем это закончится.",
            "Я бы сказал, что мне жаль. Но ты знаешь, что это неправда.",
            "Снова начало. Или очередное повторение? Я уже путаюсь.",
            "Поднимайся. У нас ещё слишком много незаконченных дел."
    );
    private ObserverDialogue() {}
    public static String firstAwakening() {
        return "Наконец-то. Я уже начал думать, что ты не проснёшься.";
    }
    public static String afterDeath(int deathCount) {
        if (deathCount <= 0) return "Любопытно. На этот раз ты всё-таки выжил.";
        return DEATH_LINES.get(Math.floorMod(deathCount - 1, DEATH_LINES.size()));
    }
}
